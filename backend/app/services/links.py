"""Signed tracked links for auction URLs (FR §6.1).

The token carries the destination generated by our server and an HMAC
signature; the redirect endpoint refuses tampered tokens and destinations
outside the allowed The Tender hosts.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import re
from dataclasses import dataclass
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

SOURCES = {"S": "SEARCH", "N": "NOTIFICATION", "C": "CAMPAIGN"}
_SIG_BYTES = 12


def _b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _unb64(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


@dataclass(frozen=True)
class LinkTarget:
    user_id: int
    source: str  # SEARCH | NOTIFICATION | CAMPAIGN
    url: str
    auction_number: str | None


def allowed_hosts(base_url: str) -> set[str]:
    hosts = {"thetender.com.ua", "www.thetender.com.ua", "sandbox.mxuser.com"}
    host = urlsplit(base_url).hostname
    if host:
        hosts.add(host)
    return hosts


def is_allowed_destination(url: str, hosts: set[str]) -> bool:
    parts = urlsplit(url)
    return parts.scheme in ("https", "http") and (parts.hostname or "") in hosts


def make_token(
    key: bytes, user_id: int, url: str, source: str, auction_number: str | None = None
) -> str:
    code = {v: k for k, v in SOURCES.items()}[source]
    payload: dict = {"u": user_id, "s": code, "l": url}
    if auction_number:
        payload["n"] = auction_number
    body = _b64(json.dumps(payload, separators=(",", ":"), ensure_ascii=False).encode())
    sig = _b64(hmac.new(key, body.encode(), hashlib.sha256).digest()[:_SIG_BYTES])
    return f"{body}.{sig}"


def parse_token(key: bytes, token: str) -> LinkTarget | None:
    try:
        body, sig = token.split(".", 1)
        expected = _b64(hmac.new(key, body.encode(), hashlib.sha256).digest()[:_SIG_BYTES])
        if not hmac.compare_digest(sig, expected):
            return None
        data = json.loads(_unb64(body))
        return LinkTarget(
            user_id=int(data["u"]),
            source=SOURCES[data["s"]],
            url=str(data["l"]),
            auction_number=data.get("n"),
        )
    except (ValueError, KeyError, TypeError):
        return None


def tracked_url(
    public_base_url: str | None,
    key: bytes | None,
    user_id: int,
    url: str,
    source: str,
    auction_number: str | None = None,
) -> str:
    """Tracked redirect URL, or the original URL when tracking is not configured."""
    if not public_base_url or not key:
        return url
    return f"{public_base_url}/r/{make_token(key, user_id, url, source, auction_number)}"


# ---------- UTM tags for links to thetender.com.ua (GA4 attribution) ----------

UTM_SOURCE = "telegram"  # replaced at startup by configure_utm()
UTM_MEDIUM = "bot"


def configure_utm(source: str) -> None:
    """telegram on the main bot; empty on the test bot — then links carry no UTM
    tags at all (existing ones are removed), so tests never reach GA4 reports."""
    global UTM_SOURCE
    UTM_SOURCE = re.sub(r"[^a-z0-9_-]+", "", (source or "").lower())


# utm_campaign values by scenario.
LOT_ALERT, DIGEST, SEARCH, MENU, REMINDER, SUPPORT = (
    "lot_alert", "digest", "search", "menu", "reminder", "support"
)  # fmt: skip
_LOT_ID = re.compile(r"^[A-Z0-9][A-Z0-9-]{3,63}$")


def _slug(value: str) -> str:
    """Latin, lowercase, words joined with «_»."""
    return re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")[:64]


def is_tender_site(url: str) -> bool:
    """The marketplace site itself (not this bot's own tg.* service host)."""
    return (urlsplit(url).hostname or "").lower() in ("thetender.com.ua", "www.thetender.com.ua")


def with_utm(url: str, campaign: str, content: str | None = None) -> str:
    """Add utm_* to a thetender.com.ua link; other sites are returned unchanged.

    Existing utm_* parameters are replaced, other query parameters and the
    #fragment are kept. No personal data ever goes into the tags.
    """
    if not url or not is_tender_site(url):
        return url
    parts = urlsplit(url)
    if not parts.path:
        parts = parts._replace(path="/")
    query = [(k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True)
             if not k.lower().startswith("utm_")]  # fmt: skip
    if not UTM_SOURCE:  # test bot: no tags
        return urlunsplit(parts._replace(query=urlencode(query)))
    query += [("utm_source", UTM_SOURCE), ("utm_medium", UTM_MEDIUM)]
    query.append(("utm_campaign", _slug(campaign)))
    if content:
        # A lot id stays as is (e.g. LAE001-UA-20261008-38094); names are slugified.
        value = content if _LOT_ID.match(content) else _slug(content)
        if value:
            query.append(("utm_content", value))
    return urlunsplit(parts._replace(query=urlencode(query)))


_URL_IN_TEXT = re.compile(r"https?://[^\s\"'<>]+")


def tag_text_links(text: str, campaign: str, content: str | None = None) -> str:
    """Tag every thetender.com.ua link inside a message (bare or in href)."""

    def repl(m: re.Match[str]) -> str:
        url = m.group(0)
        tail = ""
        while url and url[-1] in ".,;:!?)":  # sentence punctuation is not part of a URL
            tail = url[-1] + tail
            url = url[:-1]
        return with_utm(url.replace("&amp;", "&"), campaign, content).replace("&", "&amp;") + tail

    return _URL_IN_TEXT.sub(repl, text) if text else text


# ---------- deep links: https://t.me/<bot>?start=<source> ----------

_FIXED_SOURCES = {
    "site_header", "site_footer", "site_lot", "site_contacts", "ads",
    "site_radar", "site_popup", "site_search",
}  # fmt: skip
_GROUP_SOURCE = re.compile(r"^group_[a-z0-9_]{1,40}$")


def acquisition_source(payload: str | None) -> str | None:
    """Validated /start parameter, or None for anything unexpected."""
    value = (payload or "").strip().lower()
    if value in _FIXED_SOURCES or _GROUP_SOURCE.match(value):
        return value
    return None


_BOT_UA_MARKERS = ("bot", "crawler", "spider", "preview", "facebookexternalhit", "slurp")


def is_bot_user_agent(user_agent: str | None) -> bool:
    ua = (user_agent or "").lower()
    return not ua or any(marker in ua for marker in _BOT_UA_MARKERS)
